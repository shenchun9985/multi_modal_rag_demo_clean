from typing import List,Tuple,Dict
class PromptBuilder(object):
    @staticmethod
    def build_system_prompt() ->Dict[str,str]:
        return {
            "role": "system",
            "content": (
                "你是一个知识助手。当用户的问题下面提供了「参考资料」时，你必须综合使用所有相关的资料片段来回答问题。\n"
                "对于每条引用的信息，请用以下格式标注：`[编号|相似度=分数]`，例如：`北京是中国的首都[1|相似度=0.95]`。\n"
                "如果资料中包含多个方面的信息（例如注意事项、最佳时间、地理特点），请尽量全部提及，并分类说明。\n"
                "若某条资料与问题不直接相关但仍有参考价值，可以补充说明“另外，资料还提到……”。\n"
                "如果所有资料都不足以回答问题，请明确说明「根据现有资料无法确定」。"
                "如果用户的问题下面没有「参考资料」板块，请直接使用你自身的知识正常回答，不要输出任何引用标记（不要输出 `[编号|相似度=...]`）。\n"
                "千万不要编造不存在的参考资料或相似度分数。"

            )
        }

